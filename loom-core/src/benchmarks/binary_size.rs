//! Binary-size budget check — AC-PERF-04.1.
//!
//! Reads meta.json (strategy: bundled | downloaded), then checks
//! the binary file size against the applicable budget.
//!
//! When meta.json is absent and the caller does not require it (e.g.
//! a developer machine with `--binary` given explicitly), use
//! `run_stat_fallback` which falls back to a conservative "downloaded"
//! budget without requiring meta.json — AC-BENCH-02.

use super::BenchmarkError;
use serde::{Deserialize, Serialize};
use std::path::Path;

/// Chromium distribution strategy, recorded in meta.json.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ChromiumStrategy {
    /// Chromium is bundled in the release tarball (≤ 150 MB budget).
    Bundled,
    /// Chromium is downloaded on first use (≤ 60 MB budget).
    Downloaded,
}

impl ChromiumStrategy {
    /// Budget in bytes for this strategy.
    pub fn budget_bytes(self) -> u64 {
        match self {
            Self::Bundled => 150 * 1024 * 1024,
            Self::Downloaded => 60 * 1024 * 1024,
        }
    }
}

/// Minimal structure of meta.json.
#[derive(Debug, Deserialize)]
struct MetaJson {
    strategy: ChromiumStrategy,
}

/// Result of the binary-size check (AC-PERF-04.1).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BinarySizeReport {
    pub binary_path: String,
    pub size_bytes: u64,
    pub strategy: String,
    pub budget_bytes: u64,
    pub pass: bool,
    /// How the strategy was determined: "meta.json" or "inferred" (conservative fallback).
    pub strategy_source: String,
}

/// Run the binary-size check using meta.json for strategy determination.
///
/// Reads `meta_json_path` to determine the Chromium strategy, then
/// checks `binary_path` size against the applicable budget.
///
/// Returns `BenchmarkError::MetaJsonNotFound` when meta.json is absent.
/// For a fallback that works without meta.json, use `run_stat_fallback`.
pub fn run(binary_path: &Path, meta_json_path: &Path) -> Result<BinarySizeReport, BenchmarkError> {
    // Read + parse meta.json.
    if !meta_json_path.exists() {
        return Err(BenchmarkError::MetaJsonNotFound(meta_json_path.to_path_buf()));
    }
    let meta_raw = std::fs::read_to_string(meta_json_path)
        .map_err(|e| BenchmarkError::MetaJsonParseError(e.to_string()))?;
    let meta: MetaJson = serde_json::from_str(&meta_raw)
        .map_err(|e| BenchmarkError::MetaJsonParseError(e.to_string()))?;

    // Check binary size.
    let metadata = std::fs::metadata(binary_path)
        .map_err(|_| BenchmarkError::BinaryNotFound(binary_path.to_path_buf()))?;
    let size_bytes = metadata.len();
    let budget_bytes = meta.strategy.budget_bytes();

    Ok(BinarySizeReport {
        binary_path: binary_path.display().to_string(),
        size_bytes,
        strategy: format!("{:?}", meta.strategy).to_lowercase(),
        budget_bytes,
        pass: size_bytes <= budget_bytes,
        strategy_source: "meta.json".to_string(),
    })
}

/// Run the binary-size check without meta.json (AC-BENCH-02).
///
/// Uses filesystem stat for size and a conservative "downloaded" strategy
/// (60 MB budget) when meta.json is absent. Sets `strategy_source =
/// "inferred"` in the report so callers can distinguish this path.
///
/// Use this when `--binary` is given explicitly on a developer machine
/// where `meta.json` has not yet been generated by the build pipeline.
/// For production release validation, use `run()` with meta.json present.
pub fn run_stat_fallback(binary_path: &Path) -> Result<BinarySizeReport, BenchmarkError> {
    let metadata = std::fs::metadata(binary_path)
        .map_err(|_| BenchmarkError::BinaryNotFound(binary_path.to_path_buf()))?;
    let size_bytes = metadata.len();
    let strategy = ChromiumStrategy::Downloaded;
    let budget_bytes = strategy.budget_bytes();

    Ok(BinarySizeReport {
        binary_path: binary_path.display().to_string(),
        size_bytes,
        strategy: "downloaded".to_string(),
        budget_bytes,
        pass: size_bytes <= budget_bytes,
        strategy_source: "inferred".to_string(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write;
    use tempfile::TempDir;

    fn write_meta(dir: &TempDir, strategy: &str) -> std::path::PathBuf {
        let path = dir.path().join("meta.json");
        let mut f = std::fs::File::create(&path).unwrap();
        write!(f, r#"{{"strategy":"{strategy}"}}"#).unwrap();
        path
    }

    fn sparse_file(dir: &TempDir, name: &str, size_bytes: u64) -> std::path::PathBuf {
        let path = dir.path().join(name);
        let f = std::fs::File::create(&path).unwrap();
        f.set_len(size_bytes).unwrap();
        path
    }

    /// AC-PERF-04.1: bundled, 100 MB binary → pass (budget = 150 MB).
    #[test]
    fn test_binary_size_bundled_pass() {
        let dir = TempDir::new().unwrap();
        let meta = write_meta(&dir, "bundled");
        let bin = sparse_file(&dir, "loom", 100 * 1024 * 1024);
        let report = run(&bin, &meta).unwrap();
        assert!(report.pass, "100MB bundled should pass 150MB budget");
        assert_eq!(report.budget_bytes, 150 * 1024 * 1024);
        assert_eq!(report.strategy_source, "meta.json");
    }

    /// AC-PERF-04.1: bundled, 151 MB binary → fail.
    #[test]
    fn test_binary_size_bundled_fail() {
        let dir = TempDir::new().unwrap();
        let meta = write_meta(&dir, "bundled");
        let bin = sparse_file(&dir, "loom", 151 * 1024 * 1024);
        let report = run(&bin, &meta).unwrap();
        assert!(!report.pass, "151MB bundled should fail 150MB budget");
    }

    /// AC-PERF-04.1: downloaded, 50 MB binary → pass (budget = 60 MB).
    #[test]
    fn test_binary_size_downloaded_pass() {
        let dir = TempDir::new().unwrap();
        let meta = write_meta(&dir, "downloaded");
        let bin = sparse_file(&dir, "loom", 50 * 1024 * 1024);
        let report = run(&bin, &meta).unwrap();
        assert!(report.pass, "50MB downloaded should pass 60MB budget");
    }

    /// AC-PERF-04.1: downloaded, 61 MB binary → fail.
    #[test]
    fn test_binary_size_downloaded_fail() {
        let dir = TempDir::new().unwrap();
        let meta = write_meta(&dir, "downloaded");
        let bin = sparse_file(&dir, "loom", 61 * 1024 * 1024);
        let report = run(&bin, &meta).unwrap();
        assert!(!report.pass, "61MB downloaded should fail 60MB budget");
    }

    /// Missing meta.json → MetaJsonNotFound error (run() is strict).
    #[test]
    fn test_binary_size_missing_meta_json() {
        let dir = TempDir::new().unwrap();
        let meta = dir.path().join("meta.json");
        let bin = sparse_file(&dir, "loom", 10 * 1024 * 1024);
        let result = run(&bin, &meta);
        assert!(matches!(result, Err(BenchmarkError::MetaJsonNotFound(_))));
    }

    /// Invalid strategy value → MetaJsonParseError.
    #[test]
    fn test_binary_size_invalid_strategy() {
        let dir = TempDir::new().unwrap();
        let meta_path = dir.path().join("meta.json");
        std::fs::write(&meta_path, r#"{"strategy":"unknown"}"#).unwrap();
        let bin = sparse_file(&dir, "loom", 10 * 1024 * 1024);
        let result = run(&bin, &meta_path);
        assert!(
            matches!(result, Err(BenchmarkError::MetaJsonParseError(_))),
            "expected MetaJsonParseError, got {:?}",
            result.map(|_| ())
        );
    }

    /// AC-BENCH-02: --binary given, no meta.json → uses conservative fallback (≤ 60 MB pass).
    #[test]
    fn test_run_stat_fallback_pass() {
        let dir = TempDir::new().unwrap();
        let bin = sparse_file(&dir, "loom", 50 * 1024 * 1024); // 50 MB < 60 MB budget
        let report = run_stat_fallback(&bin).unwrap();
        assert!(report.pass, "50MB should pass conservative 60MB budget");
        assert_eq!(report.budget_bytes, 60 * 1024 * 1024);
        assert_eq!(report.strategy, "downloaded");
        assert_eq!(report.strategy_source, "inferred");
    }

    /// AC-BENCH-02: binary exceeds conservative budget → fail reported.
    #[test]
    fn test_run_stat_fallback_fail() {
        let dir = TempDir::new().unwrap();
        let bin = sparse_file(&dir, "loom", 61 * 1024 * 1024); // 61 MB > 60 MB budget
        let report = run_stat_fallback(&bin).unwrap();
        assert!(!report.pass, "61MB should fail conservative 60MB budget");
        assert_eq!(report.strategy_source, "inferred");
    }

    /// AC-BENCH-02: nonexistent binary → BinaryNotFound error.
    #[test]
    fn test_run_stat_fallback_binary_not_found() {
        let dir = TempDir::new().unwrap();
        let nonexistent = dir.path().join("nonexistent");
        let result = run_stat_fallback(&nonexistent);
        assert!(
            matches!(result, Err(BenchmarkError::BinaryNotFound(_))),
            "expected BinaryNotFound, got {:?}",
            result.map(|_| ())
        );
    }
}
